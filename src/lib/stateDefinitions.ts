/** Definition of one device state, relative to the device object. */
export interface StateDef {
	/** State ID below the device (channel prefix with `.`). */
	id: string;
	/** Name in all 11 languages. */
	name: ioBroker.Translated;
	/** Value type. */
	type: ioBroker.CommonType;
	/** Role. */
	role: string;
	/** Unit. */
	unit?: string;
	/** Readable. */
	read: boolean;
	/** Writable. */
	write: boolean;
	/** Default value. */
	def: ioBroker.StateValue;
	/** Minimum. */
	min?: number;
	/** Condition: `learning` is always created, `historyHtml` only if enabled in the instance settings. */
	when?: "learning" | "historyHtml";
}

/**
 * Build a name object with all 11 languages.
 *
 * @param texts - Texts in the order en, de, ru, pt, nl, fr, it, es, pl, uk, zh-cn
 */
function t(...texts: string[]): ioBroker.Translated {
	const [en, de, ru, pt, nl, fr, it, es, pl, uk, zh] = texts;
	return { en, de, ru, pt, nl, fr, it, es, pl, uk, "zh-cn": zh };
}

