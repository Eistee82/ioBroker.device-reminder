/**
 * Build the `common` part of a state object.
 *
 * @param def - State definition
 */
export function buildStateCommon(def: StateDef): ioBroker.StateCommon {
	const common: ioBroker.StateCommon = {
		name: def.name,
		type: def.type,
		role: def.role,
		read: def.read,
		write: def.write,
		def: def.def,
	};
	if (def.unit !== undefined) {
		common.unit = def.unit;
	}
	if (def.min !== undefined) {
		common.min = def.min;
	}
	return common;
}
